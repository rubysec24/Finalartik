// İllerin hangi bölgeye ait olduğunu bulma fonksiyonu
export const getCityRegion = (city: string): string => {
  for (const [region, cities] of Object.entries(turkeyRegions)) {
    if (cities.includes(city)) {
      return region;
    }
  }
  return "";
};

// İllerine göre bölgelere bayi sayısını hesaplama
export const getDealerCountByRegion = (dealers: any[]) => {
  const counts: Record<string, number> = {
    "Marmara": 0,
    "Ege": 0,
    "Akdeniz": 0,
    "İç Anadolu": 0,
    "Karadeniz": 0,
    "Doğu Anadolu": 0,
    "Güneydoğu Anadolu": 0
  };

  dealers.forEach(dealer => {
    const region = getCityRegion(dealer.city);
    if (region) {
      counts[region] += 1;
    }
  });

  return counts;
}; 